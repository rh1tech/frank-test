/*
 * ui_video_pio_vga.c — VGA out of the PIO, for the board HSTX cannot
 * reach.
 *
 *
 * WHY A SECOND VGA BACKEND
 *
 * The same argument that produced a second HDMI backend, one connector
 * over. HSTX is wired to GP12-19 and nowhere else. Every VGA board in
 * the fleet puts its resistor ladder there, which is why ui_video_vga.c
 * was the only VGA path for as long as that was true.
 *
 * xt8086's ladder is on GP30-37, because GP12-19 on that board are an
 * 8086's AD12-A19. So there is no hardware path to the connector, and
 * the HSTX backend must not merely fail to reach it — it must refuse,
 * which it now does, or it would clock a video signal into a live CPU's
 * address bus.
 *
 * The signal is generated by PIO instead, from the other half of the
 * murmnes driver this firmware already vendors for PIO HDMI. One
 * instruction, `out pins, 8`, running at the pixel clock, with the syncs
 * carried in the same byte as the colour — which is the same byte the
 * HSTX path builds, because both are describing the fleet's ladder:
 * B0 B1 G0 G1 R0 R1 HS VS upward from the base pin.
 *
 *
 * IT DRAWS A TEXT PAGE, NOT THE DESKTOP
 *
 * The driver scans a 320x240 indexed framebuffer doubled to 640x480, so
 * this backend inherits exactly what the PIO HDMI one does: a quarter of
 * the desktop's pixels, 6-pixel type that does not survive being halved,
 * and therefore ui_textpage.c at native resolution instead. 53 columns
 * by 30 rows.
 *
 *
 * WHERE THE FRAME LIVES
 *
 * Borrowed from the double-buffered pair, as composite and PIO HDMI do,
 * and for the same reason: this backend never scans our 153,600-byte
 * buffers, so one of the two is idle and two 76,800-byte pages fit
 * inside it with room over. Two pages rather than one because every
 * repaint begins by clearing the frame, and with a single page the
 * display shows that clear.
 */

#include "ui_video.h"

#include "ui_desktop.h"
#include "ui_gfx.h"
#include "ui_palette.h"
#include "ui_textpage.h"

/* Path-qualified for the same reason ui_video_pio_hdmi.c qualifies it:
 * drivers/ holds frank-msx's HDMI.h, and on a case-insensitive
 * filesystem a plain "hdmi.h" resolves to that one instead. */
#include "hdmi_pio/hdmi.h"

#include "pico/multicore.h"
#include "pico/stdlib.h"

#include <string.h>

#define PIO_W 320
#define PIO_H 240

/* Both pages live inside the borrowed 4 bpp buffer. If the desktop ever
 * shrinks, this path silently scribbles past the end of it, so fail the
 * build instead. */
_Static_assert(2 * PIO_W * PIO_H <= UI_FB_BYTES,
               "PIO VGA needs two pages inside one borrowed framebuffer");

static uint8_t *page;   /* what the driver is scanning */
static uint8_t *back;   /* what we are drawing */

/* Core 1 runs the scanline interrupt, as it does on every other video
 * path here. */
static void __not_in_flash_func(pio_vga_core1_run)(void) {
    graphics_init();

    /* After init, not before, and this is the trap the HDMI backend
     * already fell into: graphics_init() rebuilds the palette from its
     * own defaults, so entries uploaded ahead of the launch are thrown
     * away and the interface is drawn correctly in black on black — a
     * signal the monitor locks to, showing nothing, which reads exactly
     * like a driver that does not work. */
    for (unsigned i = 0; i < UI_PALETTE_LEN; i++)
        graphics_set_palette((uint8_t)i, ui_palette_rgb888[i]);

    while (true) tight_loop_contents();
}

static bool pio_vga_init(void) {
    /* Only the base this image's copy of the driver was compiled for.
     * On a board wired to GP12-19 the HSTX backend is better in every
     * way and sits earlier in the table; this refusing is what picks the
     * right one. */
    if (ui_video_pin_base() != VGA_BASE_PIN) return false;

    /* The driver is one file with two halves sharing PIO0, DMA_IRQ_0 and
     * conv_color[]. This flag is what decides which half graphics_init()
     * and graphics_set_palette() dispatch to, and it must be set before
     * either is called - core 1 calls both. */
    SELECT_VGA = true;

    /* Two pages, both inside the borrowed buffer. It is a 640x480 4 bpp
     * screen - 153,600 bytes - and a page here is 320x240 at 8 bpp. */
    page = ui_video_spare_bits();
    back = page + (size_t)PIO_W * PIO_H;
    memset(page, 0, (size_t)PIO_W * PIO_H * 2);

    graphics_set_res(PIO_W, PIO_H);
    graphics_set_buffer(page);
    ui_textpage_target(back, PIO_W, PIO_H);

    multicore_reset_core1();
    multicore_launch_core1(pio_vga_core1_run);
    return true;
}

static void pio_vga_present(void) {
    /* Draw into the page the driver is not scanning, then hand it over.
     * Identical to the PIO HDMI path, including why: drawing straight
     * into the live page shows the clear-to-black that starts every
     * repaint, so the screen flashes on each keypress. There is no
     * vertical blank to synchronise with this side of the ISR, so the
     * answer is to make the visible page never be the one under
     * construction. The swap is one pointer, read per scanline. */
    if (!ui_textpage_ready()) return;

    ui_textpage_draw();

    uint8_t *shown = back;
    back = page;
    page = shown;

    graphics_set_buffer(shown);
    ui_textpage_target(back, PIO_W, PIO_H);
}

/* From the driver's ISR, not from present(): the Video output row asks
 * whether frames reached the connector, and repaints are not evidence of
 * that. */
static uint32_t pio_vga_frames(void) { return vga_pio_frame_count; }

const ui_video_backend_t ui_video_backend_pio_vga = {
    .name     = "PIO VGA 640x480",
    .mode     = VIDEO_VGA,
    .init     = pio_vga_init,
    /* No shutdown, as everywhere else here: unwinding the DMA chain, the
     * exclusive handler and core 1 is more risk than the reboot
     * ui_video_switch() does instead. */
    .shutdown = NULL,
    .present  = pio_vga_present,
    .frames   = pio_vga_frames,
};
